//! Shared knowledge hub (decision 0036): the hub's Related Repositories table
//! names member repositories, and each member's `CLAUDE.md` carries a marked
//! block pointing back to the hub.

use std::fmt::{Display, Formatter};

pub const HUB_BEGIN: &str = "<!-- HARNESS-HUB:BEGIN -->";
pub const HUB_END: &str = "<!-- HARNESS-HUB:END -->";
const MAP_HEADING: &str = "## Related Repositories";

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct HubMember {
    pub name: String,
    /// Path relative to the hub, as written in the table.
    pub location: String,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct HubMapError(pub String);

impl Display for HubMapError {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> std::fmt::Result {
        self.0.fmt(formatter)
    }
}

impl std::error::Error for HubMapError {}

/// Members are rows of the Related Repositories table whose Location is a
/// relative path; rows with a URL are not checked out and are skipped.
pub fn parse_hub_members(readme: &str) -> Result<Vec<HubMember>, HubMapError> {
    let mut lines = readme.lines().skip_while(|line| line.trim() != MAP_HEADING);
    if lines.next().is_none() {
        return Err(HubMapError(format!(
            "docs/README.md has no `{MAP_HEADING}` section listing member repositories"
        )));
    }
    let rows = lines
        .take_while(|line| !line.starts_with("## ") && !line.starts_with("### "))
        .map(str::trim)
        .skip_while(|line| !line.starts_with('|'))
        .take_while(|line| line.starts_with('|'))
        .skip(2); // header and separator
    let mut members: Vec<HubMember> = Vec::new();
    for row in rows {
        let cells = row
            .trim_matches('|')
            .split('|')
            .map(|cell| cell.trim().trim_matches('`').trim())
            .collect::<Vec<_>>();
        let (name, location) = match cells.as_slice() {
            [name, _role, location, ..] => (*name, *location),
            _ => return Err(HubMapError(format!("table row needs three cells: {row}"))),
        };
        if name.is_empty() && location.is_empty() {
            continue;
        }
        if location.contains("://") || location.starts_with("git@") {
            continue;
        }
        let valid_name = !name.is_empty()
            && name != "."
            && name != ".."
            && name
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'));
        if !valid_name {
            return Err(HubMapError(format!(
                "repository name `{name}` must use only letters, digits, '.', '_', or '-'"
            )));
        }
        if location.is_empty()
            || location.starts_with('/')
            || location.starts_with('~')
            || location.contains('\\')
        {
            return Err(HubMapError(format!(
                "location for `{name}` must be a path relative to the hub, got `{location}`"
            )));
        }
        if members.iter().any(|member| member.name == name) {
            return Err(HubMapError(format!("repository `{name}` is listed twice")));
        }
        members.push(HubMember {
            name: name.to_owned(),
            location: location.to_owned(),
        });
    }
    Ok(members)
}

/// The pointer block for one member. `hub_path` is the hub as seen from the
/// member, for example `../system-knowledge`.
pub fn render_hub_block(hub_path: &str, member: &str) -> String {
    render_block(
        &format!(
            "This repository belongs to a multi-repository system whose knowledge lives in
the hub repository at `{hub_path}` (relative to this repository). Generated by
`harness hub sync` in the hub; edit the hub, not this block."
        ),
        &format!("Knowledge specific to this repository: `{hub_path}/docs/services/{member}/`."),
        hub_path,
    )
}

/// The pointer block for the workspace directory that holds the hub and its
/// members. Claude Code loads it in every member below that directory, so
/// `hub_path` is absolute.
pub fn render_workspace_block(hub_path: &str) -> String {
    render_block(
        &format!(
            "Repositories under this directory belong to a multi-repository system whose
knowledge lives in the hub repository at `{hub_path}`. Generated by
`harness hub sync --workspace` in the hub; edit the hub, not this block."
        ),
        &format!(
            "Knowledge specific to one repository: `{hub_path}/docs/services/<repository>/`,
  where `<repository>` is its row under Related Repositories in
  `{hub_path}/docs/README.md`."
        ),
        hub_path,
    )
}

fn render_block(intro: &str, member_line: &str, hub_path: &str) -> String {
    format!(
        "{HUB_BEGIN}
## Shared Knowledge Hub

{intro}

- System map, decisions, interface contracts, and plans: `{hub_path}/docs/`.
- {member_line}

Read the hub before deciding anything beyond this repository's code, and record
new decisions, contracts, and plans there rather than here. If the hub is not
checked out at that path, report it as a missing capability.
{HUB_END}
"
    )
}

/// Replace the marked block in `existing`, or append it; text outside the
/// markers is kept byte for byte.
pub fn apply_hub_block(existing: Option<&str>, block: &str) -> Result<String, HubMapError> {
    let Some(existing) = existing else {
        return Ok(block.to_owned());
    };
    let begins = existing.matches(HUB_BEGIN).count();
    let ends = existing.matches(HUB_END).count();
    match (begins, ends) {
        (0, 0) => {
            let separator = if existing.is_empty() {
                ""
            } else if existing.ends_with('\n') {
                "\n"
            } else {
                "\n\n"
            };
            Ok(format!("{existing}{separator}{block}"))
        }
        (1, 1) => {
            let start = existing.find(HUB_BEGIN).unwrap();
            let end = existing.find(HUB_END).unwrap();
            if end < start {
                return Err(HubMapError("hub markers are out of order".to_owned()));
            }
            let mut after = &existing[end + HUB_END.len()..];
            after = after.strip_prefix('\n').unwrap_or(after);
            Ok(format!("{}{block}{after}", &existing[..start]))
        }
        _ => Err(HubMapError(
            "CLAUDE.md must contain exactly one complete hub marker pair".to_owned(),
        )),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const MAP: &str = "# Map\n\n## Related Repositories\n\nIntro.\n\n\
| Repository | Role | Location |\n| --- | --- | --- |\n\
| orders-service | service | `../orders-service` |\n\
| app-config | environment configuration | ../app-config |\n\
| remote-lib | shared library | https://example.invalid/lib.git |\n\n\
### Authority By Truth Type\n\n| Truth type | Source | Path |\n| --- | --- | --- |\n| x | y | z |\n";

    #[test]
    fn parses_relative_rows_and_skips_urls_and_later_tables() {
        let members = parse_hub_members(MAP).unwrap();
        assert_eq!(
            members,
            vec![
                HubMember {
                    name: "orders-service".into(),
                    location: "../orders-service".into()
                },
                HubMember {
                    name: "app-config".into(),
                    location: "../app-config".into()
                },
            ]
        );
    }

    #[test]
    fn rejects_absolute_locations_unsafe_names_duplicates_and_missing_section() {
        let absolute = MAP.replace("../app-config", "/home/me/app-config");
        assert!(parse_hub_members(&absolute)
            .unwrap_err()
            .0
            .contains("relative to the hub"));
        let traversal = MAP.replace("| orders-service |", "| ../x |");
        assert!(parse_hub_members(&traversal).is_err());
        let duplicate = MAP.replace("| app-config |", "| orders-service |");
        assert!(parse_hub_members(&duplicate)
            .unwrap_err()
            .0
            .contains("twice"));
        assert!(parse_hub_members("# nothing\n").is_err());
    }

    #[test]
    fn empty_template_table_has_no_members() {
        let empty =
            "## Related Repositories\n\n| Repository | Role | Location |\n| --- | --- | --- |\n";
        assert_eq!(parse_hub_members(empty).unwrap(), Vec::new());
    }

    #[test]
    fn applies_appends_and_replaces_only_the_marked_block() {
        let block = render_hub_block("../hub", "orders");
        assert_eq!(apply_hub_block(None, &block).unwrap(), block);

        let appended = apply_hub_block(Some("# Team\nkeep me"), &block).unwrap();
        assert!(appended.starts_with("# Team\nkeep me\n\n"));
        assert!(appended.ends_with(&block));

        let newer = render_hub_block("../knowledge", "orders");
        let replaced = apply_hub_block(Some(&format!("{appended}after\n")), &newer).unwrap();
        assert_eq!(replaced, format!("# Team\nkeep me\n\n{newer}after\n"));
        assert_eq!(apply_hub_block(Some(&replaced), &newer).unwrap(), replaced);

        let workspace = render_workspace_block("/w/hub");
        assert!(workspace.contains("`/w/hub/docs/services/<repository>/`"));
        assert!(workspace.contains("`harness hub sync --workspace`"));

        let broken = format!("{HUB_BEGIN}\nno end\n");
        assert!(apply_hub_block(Some(&broken), &block).is_err());
    }
}
